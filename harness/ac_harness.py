"""In-game test harness for development (Windows, Assetto Corsa + Content Manager). First run at M3.

Never part of a public build: AC's licence covers personal use only.

Content Manager (CM) is the preferred way in:

    python harness/ac_harness.py showroom out/<id>/05_track/<id>/<id>_forward.kn5   # look at the model first
    python harness/ac_harness.py install out/<id>/05_track/<id>          # copy into content/tracks
    python harness/ac_harness.py install-cm out/<id>/05_track/<id>.zip   # or let CM install the zip
    python harness/ac_harness.py launch <id> --layout forward            # practice session via CM
    python harness/ac_harness.py probe                                   # while driving: wheels, position
    python harness/ac_harness.py results                                 # after the session: race_out.json
    python harness/ac_harness.py check-log <id>                          # after AC closes: log.txt + CSP log

`prepare` and `restore` patch Documents/Assetto Corsa/cfg/race.ini directly,
for starting AC without CM.

Configuration comes from env vars or config.local.toml:
- `ac_root` / MAPCREATOR_AC_ROOT: the folder with acs.exe.
- `cm_path` / MAPCREATOR_CM_PATH: Content Manager.exe.
- MAPCREATOR_AC_DOCS: default ~/Documents/Assetto Corsa.

Sources (see THIRD_PARTY_NOTICES.md):
- The load-test rules follow an open-source generator's harness.
- CM's URI routes and file arguments, and the shared-memory offsets, come
  from Content Manager's source and the public SPageFile layouts.
"""

from __future__ import annotations

import argparse
import configparser
import io
import json
import mmap
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import time
import tomllib
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
MARKER = "generated by mapcreator"


def _config(key: str, env: str) -> str | None:
    value = os.environ.get(env)
    cfg = ROOT / "config.local.toml"
    if not value and cfg.exists():
        value = tomllib.loads(cfg.read_text(encoding="utf-8")).get(key)
    return value


def ac_root() -> Path:
    value = _config("ac_root", "MAPCREATOR_AC_ROOT")
    if not value:
        sys.exit("set MAPCREATOR_AC_ROOT or ac_root in config.local.toml")
    path = Path(value)
    if not (path / "acs.exe").exists():
        sys.exit(f"{path} does not contain acs.exe")
    return path


def cm_path() -> Path:
    value = _config("cm_path", "MAPCREATOR_CM_PATH")
    if not value or not Path(value).exists():
        sys.exit("set MAPCREATOR_CM_PATH or cm_path in config.local.toml to Content Manager.exe")
    return Path(value)


def _documents() -> Path:
    """The shell's Documents folder, which AC, CM and CSP all use. OneDrive often moves it away from
    ~/Documents, so ask Windows rather than guess."""
    if sys.platform == "win32":
        import ctypes
        from ctypes import wintypes

        class GUID(ctypes.Structure):
            _fields_ = [("Data1", wintypes.DWORD), ("Data2", wintypes.WORD), ("Data3", wintypes.WORD),
                        ("Data4", ctypes.c_ubyte * 8)]

        documents = GUID(0xFDD39AD0, 0x238F, 0x46AF, (ctypes.c_ubyte * 8)(0xAD, 0xB4, 0x6C, 0x85, 0x48, 0x03, 0x69, 0xC7))
        found = ctypes.c_wchar_p()
        if ctypes.windll.shell32.SHGetKnownFolderPath(ctypes.byref(documents), 0, None, ctypes.byref(found)) == 0:
            try:
                return Path(found.value)
            finally:
                ctypes.windll.ole32.CoTaskMemFree(found)
    return Path.home() / "Documents"


def ac_docs() -> Path:
    value = _config("ac_docs", "MAPCREATOR_AC_DOCS")
    return Path(value) if value else _documents() / "Assetto Corsa"


def _cm(*args: str) -> None:
    """Hand a file or acmanager:// URI to Content Manager (it reuses a running instance)."""
    subprocess.Popen([str(cm_path()), *args])


# -- install ---------------------------------------------------------------------

def install(track_dir: Path) -> None:
    tid = track_dir.name
    dest = ac_root() / "content" / "tracks" / tid
    if dest.exists():
        attribution = dest / "ATTRIBUTION.txt"
        if not (attribution.exists() and MARKER in attribution.read_text(encoding="utf-8", errors="ignore")):
            sys.exit(f"{dest} exists and was not made by mapcreator; refusing to overwrite it")
        shutil.rmtree(dest)
    shutil.copytree(track_dir, dest)
    # AC caches AI grids and payloads per track; stale ones survive a reinstall.
    cache = ac_root() / "cache"
    removed = 0
    for sub in ("ai_grids", "ai_payloads"):
        for p in (cache / sub).glob(f"{tid}__*"):
            p.unlink()
            removed += 1
    print(f"installed {tid} -> {dest} (cleared {removed} cached AI files)")


# -- race.ini --------------------------------------------------------------------

def _race_ini() -> Path:
    return ac_docs() / "cfg" / "race.ini"


def _first_skin(car: str) -> str:
    skins = ac_root() / "content" / "cars" / car / "skins"
    found = sorted(p.name for p in skins.iterdir() if p.is_dir()) if skins.is_dir() else []
    return found[0] if found else ""


def _patched_race_ini(tid: str, layout: str, car: str) -> str:
    """The player's last race.ini, made into a solo practice session on the track.

    Their own settings (weather, lighting, assists) stay. Everything that would turn the launch into
    something else is cleared, as Content Manager's own clean-up does: an online server, a replay, a
    benchmark or a restart; extra cars and sessions from a race weekend; events; and the last car's
    skin and setup.
    """
    ini = _race_ini()
    if not ini.exists():
        sys.exit(f"{ini} doesn't exist: start any session in Content Manager once, then try again")
    cp = configparser.ConfigParser(strict=False, interpolation=None)
    cp.optionxform = str
    cp.read(ini, encoding="utf-8-sig")
    for name in cp.sections():
        if (name.startswith(("CAR_", "SESSION_", "CONDITION_")) and name not in ("CAR_0", "SESSION_0")) \
                or name in ("EVENT", "SPECIAL_EVENT"):
            cp.remove_section(name)
    if cp.has_section("CAR_0"):
        cp.remove_option("CAR_0", "_EXT_SETUP_FILENAME")
    for section, values in {
        "RACE": {"TRACK": tid, "CONFIG_TRACK": layout, "MODEL": car, "CARS": "1", "PENALTIES": "0"},
        "CAR_0": {"MODEL": "-", "DRIVER_NAME": "Test", "SKIN": _first_skin(car), "SETUP": ""},
        "SESSION_0": {"NAME": "Practice", "TYPE": "1", "DURATION_MINUTES": "0", "SPAWN_SET": "PIT"},
        "REMOTE": {"ACTIVE": "0"},
        "REPLAY": {"ACTIVE": "0"},
        "BENCHMARK": {"ACTIVE": "0"},
        "RESTART": {"ACTIVE": "0"},
        "AUTOSPAWN": {"ACTIVE": "1"},
    }.items():
        if not cp.has_section(section):
            cp.add_section(section)
        for k, v in values.items():
            cp.set(section, k, v)
    buf = io.StringIO()
    cp.write(buf, space_around_delimiters=False)
    return buf.getvalue()


def prepare(tid: str, layout: str, car: str) -> None:
    ini = _race_ini()
    backup = ini.with_suffix(".ini.mapcreator-backup")
    if not backup.exists():
        shutil.copy2(ini, backup)
    ini.write_text(_patched_race_ini(tid, layout, car), encoding="utf-8")
    print(f"race.ini set to {tid}/{layout or '(main)'} with {car}; backup at {backup}")


def restore() -> None:
    ini = _race_ini()
    backup = ini.with_suffix(".ini.mapcreator-backup")
    if not backup.exists():
        sys.exit("no backup to restore")
    shutil.copy2(backup, ini)
    backup.unlink()
    print("race.ini restored")


def launch(tid: str, layout: str, car: str) -> None:
    """Start a fully specified practice session through CM's acmanager://race/config route.

    CM writes the race.ini itself and starts AC through the user's configured
    starter. AC still waits in the pits menu until Drive is pressed.
    """
    path = Path(tempfile.gettempdir()) / f"mapcreator_{tid}_{layout or 'main'}_race.ini"
    path.write_text(_patched_race_ini(tid, layout, car), encoding="utf-8")
    uri = f"acmanager://race/config?configFile={quote(str(path), safe='')}"
    _cm(uri)
    print(f"asked Content Manager to start {tid}/{layout or '(main)'} with {car}")


# -- checks ----------------------------------------------------------------------

def check_log(tid: str) -> int:
    logs = ac_docs() / "logs"
    lines = (logs / "log.txt").read_text(encoding="utf-8", errors="ignore").splitlines()
    # Vanilla AC logs "LOADING MODEL content/tracks/<id>"; with CSP 0.2.11 that line is gone (M3), and
    # "Creating physics track: <id> [<layout>]" is what's left. The physics start below confirms the load.
    physics_track = f"Creating physics track: {tid}"
    loaded = any(f"LOADING MODEL content/tracks/{tid}" in ln
                 or ln.strip() == physics_track or ln.strip().startswith(physics_track + " [")
                 for ln in lines)
    physics = any(ln.strip() == "STARTING PHYSICS ENGINE" for ln in lines)
    errors = [ln for ln in lines if tid in ln and "ERROR:" in ln and f"NO STAT FOR {tid}" not in ln
              and not ln.startswith("Saving replay:")]
    print(f"track model loaded: {loaded}\nphysics started: {physics}\nerrors naming the track: {len(errors)}")
    for ln in errors[:20]:
        print("  ", ln)
    csp = logs / "custom_shaders_patch.log"
    csp_errors = []
    if csp.exists():
        csp_lines = csp.read_text(encoding="utf-8", errors="ignore").splitlines()
        # CSP marks failures with 💥 rather than the word ERROR ("💥 Failed to load trees: ..." in M3).
        csp_errors = [ln for ln in csp_lines
                      if ("ERROR" in ln.upper() or "💥" in ln or "FAILED" in ln.upper())
                      and (tid in ln or "ext_config" in ln.lower())]
        nodes = [ln.split("Setting chunks for:", 1)[1].strip() for ln in csp_lines if f"Setting chunks for: {tid}," in ln]
        print(f"CSP model nodes: {nodes[-1] if nodes else 'not logged'}")
        trees = [ln.split("🚀", 1)[1].strip() for ln in csp_lines if "Loading trees:" in ln]
        print(f"CSP trees: {trees[-1] if trees else 'none listed'}")
        print(f"CSP log errors naming the track or its config: {len(csp_errors)}")
        for ln in csp_errors[:20]:
            print("  ", ln)
    return 0 if loaded and physics and not errors and not csp_errors else 1


def _mapping_exists(name: str) -> bool:
    import ctypes

    FILE_MAP_READ = 0x0004
    kernel32 = ctypes.windll.kernel32
    kernel32.OpenFileMappingW.restype = ctypes.c_void_p
    handle = kernel32.OpenFileMappingW(FILE_MAP_READ, False, name)
    if not handle:
        return False
    kernel32.CloseHandle(ctypes.c_void_p(handle))
    return True


def probe(samples: int = 3) -> int:
    """Physics page: speed, wheel loads, suspension. Graphics page: status and car position."""
    if not (_mapping_exists("Local\\acpmf_physics") and _mapping_exists("Local\\acpmf_graphics")):
        # mmap with a tagname would quietly create an empty mapping under AC's name instead.
        print("AC's shared memory isn't there: is AC running, and in a session?")
        return 1
    try:
        phys = mmap.mmap(-1, 512, tagname="Local\\acpmf_physics", access=mmap.ACCESS_READ)
        graph = mmap.mmap(-1, 512, tagname="Local\\acpmf_graphics", access=mmap.ACCESS_READ)
    except OSError as e:
        print(f"shared memory not available (is AC running?): {e}")
        return 1
    ok = True
    for i in range(samples):
        phys.seek(0)
        p = phys.read(200)
        graph.seek(0)
        g = graph.read(264)
        speed = struct.unpack_from("<f", p, 28)[0]
        loads = struct.unpack_from("<4f", p, 72)
        status = struct.unpack_from("<i", g, 4)[0]  # 0 off, 1 replay, 2 live, 3 pause
        progress = struct.unpack_from("<f", g, 248)[0]
        pos = struct.unpack_from("<3f", g, 252)
        good = all(v == v and v > 100 for v in loads)
        ok &= good
        print(f"status {status} speed {speed:6.1f} km/h  wheel loads {[round(v) for v in loads]} N  "
              f"position {[round(c, 2) for c in pos]}  progress {progress:.3f}  "
              f"{'OK' if good else 'NOT ALL WHEELS LOADED'}")
        if i < samples - 1:
            time.sleep(1)
    return 0 if ok else 1


def results() -> int:
    """Times from AC's race_out.json. A point-to-point run is one lap; one the AI drove has time -1 (M3)."""
    path = ac_docs() / "out" / "race_out.json"
    if not path.exists():
        print(f"{path} not found")
        return 1
    data = json.loads(path.read_text(encoding="utf-8", errors="ignore"))
    print(f"track: {data.get('track')}")
    for s in data.get("sessions", []):
        laps = s.get("laps", [])
        print(f"session {s.get('name')} ({len(laps)} laps)")
        for lap in laps:
            t = lap.get("time", 0)
            print(f"  lap {lap.get('lap')}: {t / 1000:.3f} s  cuts {lap.get('cuts')}  sectors {lap.get('sectors')}")
    return 0


# -- automated probe (CSP Lua app) --------------------------------------------------

PROBE_APP = ROOT / "harness" / "csp_app" / "mc_probe"
TELEPORT_TOLERANCE_M = 3.0
MAX_WHEEL_GAP_M = 1.0  # car centre to wheel contact, vertically


def _probe_dir() -> Path:
    return ac_docs() / "mapcreator_probe"


def probe_install() -> None:
    dest = ac_root() / "apps" / "lua" / "mc_probe"
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(PROBE_APP, dest)
    print(f"installed the probe app -> {dest} (needs Custom Shaders Patch)")


def probe_points(track_dir: Path, layout: str, every_m: float, quit_after: bool, shots_every: int) -> None:
    """Points along the layout's AI line (already 0.4 m above the road) for the Lua app to visit."""
    sys.path.insert(0, str(ROOT / "src"))
    from mapcreator.core import ai_line  # the harness runs from the repo's venv

    base = track_dir / layout if layout else track_dir
    line = ai_line.read(base / "ai" / "fast_lane.ai")
    step = max(int(round(every_m / max(float(line.length[1] - line.length[0]), 1e-6))), 1)
    pts = []
    for i in range(0, len(line.pos), step):
        fwd = line.extra[i, 13:16]
        pts.append({"pos": [round(float(v), 3) for v in line.pos[i] + [0.0, 0.6, 0.0]],
                    "dir": [round(float(v), 4) for v in fwd], "s_m": round(float(line.length[i]), 1)})
    out = _probe_dir()
    out.mkdir(parents=True, exist_ok=True)
    for old in ("results.json", "status.json"):
        (out / old).unlink(missing_ok=True)
    (out / "points.json").write_text(json.dumps({"points": pts, "quit": quit_after,
                                                 "screenshots_every": shots_every}), encoding="utf-8")
    print(f"wrote {len(pts)} probe points every ~{every_m:.0f} m to {out / 'points.json'}")


def probe_report() -> int:
    path = _probe_dir() / "results.json"
    if not path.exists():
        print(f"{path} not found (has the probe finished?)")
        return 1
    data = json.loads(path.read_text(encoding="utf-8"))
    problems, n = [], 0
    for r in data.get("results", []):
        n += 1
        req, pos = r["requested"], r["position"]
        moved = sum((a - b) ** 2 for a, b in zip(req, pos)) ** 0.5
        if moved > TELEPORT_TOLERANCE_M:
            problems.append(f"point {r['i']}: teleport ignored or car slid {moved:.1f} m (harness issue, not track)")
            continue
        gaps = [pos[1] - w["contact"][1] for w in r["wheels"]]
        if any(g > MAX_WHEEL_GAP_M or g < -0.5 for g in gaps):
            problems.append(f"point {r['i']}: wheel contact gaps {[round(g, 2) for g in gaps]} m")
        if not all(w["valid_track"] for w in r["wheels"]):
            problems.append(f"point {r['i']}: a wheel is not on valid track")
        if r.get("raycast_m", -1) < 0:
            problems.append(f"point {r['i']}: downward raycast found no surface (hole in collision)")
        if abs(r.get("lateral", 0)) > 1.0:
            problems.append(f"point {r['i']}: {r['lateral']:.2f} outside the AI spline's width")
    print(f"probe points checked: {n}, CSP build {data.get('csp')}")
    fps = sorted(r["fps"] for r in data.get("results", []) if isinstance(r.get("fps"), (int, float)))
    if fps:
        print(f"frame rate at the points: min {fps[0]:.0f}, median {fps[len(fps) // 2]:.0f}, max {fps[-1]:.0f} fps")
    for p in problems[:50]:
        print("  ", p)
    print("PASS" if n and not problems else "FAIL")
    return 0 if n and not problems else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="ac_harness")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("showroom")
    p.add_argument("kn5", type=Path)
    p = sub.add_parser("install")
    p.add_argument("track_dir", type=Path)
    p = sub.add_parser("install-cm")
    p.add_argument("zip", type=Path)
    for name in ("prepare", "launch"):
        p = sub.add_parser(name)
        p.add_argument("track_id")
        p.add_argument("--layout", default="forward", help="layout folder; empty string for single-layout tracks")
        p.add_argument("--car", default="abarth500")
    sub.add_parser("restore")
    p = sub.add_parser("check-log")
    p.add_argument("track_id")
    sub.add_parser("probe")
    sub.add_parser("results")
    sub.add_parser("probe-install")
    p = sub.add_parser("probe-points")
    p.add_argument("track_dir", type=Path)
    p.add_argument("--layout", default="forward")
    p.add_argument("--every", type=float, default=200.0, help="metres between probe points")
    p.add_argument("--quit", action="store_true", help="quit AC when the probe finishes")
    p.add_argument("--screenshots-every", type=int, default=0, help="screenshot every Nth point (0 = none)")
    sub.add_parser("probe-report")
    args = ap.parse_args(argv)
    if args.cmd == "probe-install":
        probe_install()
        return 0
    if args.cmd == "probe-points":
        probe_points(args.track_dir, args.layout, args.every, args.quit, args.screenshots_every)
        return 0
    if args.cmd == "probe-report":
        return probe_report()
    if args.cmd == "showroom":
        _cm(str(args.kn5.resolve()))
    elif args.cmd == "install":
        install(args.track_dir)
    elif args.cmd == "install-cm":
        _cm(str(args.zip.resolve()))
    elif args.cmd == "prepare":
        prepare(args.track_id, args.layout, args.car)
    elif args.cmd == "launch":
        launch(args.track_id, args.layout, args.car)
    elif args.cmd == "restore":
        restore()
    elif args.cmd == "check-log":
        return check_log(args.track_id)
    elif args.cmd == "probe":
        return probe()
    elif args.cmd == "results":
        return results()
    return 0


if __name__ == "__main__":
    sys.exit(main())
