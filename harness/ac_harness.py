"""In-game test harness for development (Windows, Assetto Corsa + Content Manager). UNTESTED until M3.

Never part of a public build: AC's licence covers personal use only.

Content Manager (CM) is the preferred way in:

    python harness/ac_harness.py showroom out/<id>/05_track/<id>/<id>_forward.kn5   # look at the model first
    python harness/ac_harness.py install out/<id>/05_track/<id>          # copy into content/tracks
    python harness/ac_harness.py install-cm out/<id>/05_track/<id>.zip   # or let CM install the zip
    python harness/ac_harness.py launch <id> --layout forward            # practice session via CM
    python harness/ac_harness.py probe                                   # while driving: wheels, position
    python harness/ac_harness.py results                                 # after the session: race_out.json
    python harness/ac_harness.py check-log <id>                          # after AC closes: log.txt + CSP log

`prepare` and `restore` patch Documents/Assetto Corsa/cfg/race.ini directly,
for starting AC without CM.

Configuration comes from env vars or config.local.toml:
- `ac_root` / MAPCREATOR_AC_ROOT: the folder with acs.exe.
- `cm_path` / MAPCREATOR_CM_PATH: Content Manager.exe.
- MAPCREATOR_AC_DOCS: default ~/Documents/Assetto Corsa.

Sources (see THIRD_PARTY_NOTICES.md):
- The load-test rules follow an open-source generator's harness.
- CM's URI routes and file arguments, and the shared-memory offsets, come
  from Content Manager's source and the public SPageFile layouts.
"""

from __future__ import annotations

import argparse
import configparser
import io
import json
import mmap
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import time
import tomllib
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
MARKER = "generated by mapcreator"


def _config(key: str, env: str) -> str | None:
    value = os.environ.get(env)
    cfg = ROOT / "config.local.toml"
    if not value and cfg.exists():
        value = tomllib.loads(cfg.read_text(encoding="utf-8")).get(key)
    return value


def ac_root() -> Path:
    value = _config("ac_root", "MAPCREATOR_AC_ROOT")
    if not value:
        sys.exit("set MAPCREATOR_AC_ROOT or ac_root in config.local.toml")
    path = Path(value)
    if not (path / "acs.exe").exists():
        sys.exit(f"{path} does not contain acs.exe")
    return path


def cm_path() -> Path:
    value = _config("cm_path", "MAPCREATOR_CM_PATH")
    if not value or not Path(value).exists():
        sys.exit("set MAPCREATOR_CM_PATH or cm_path in config.local.toml to Content Manager.exe")
    return Path(value)


def ac_docs() -> Path:
    return Path(os.environ.get("MAPCREATOR_AC_DOCS", Path.home() / "Documents" / "Assetto Corsa"))


def _cm(*args: str) -> None:
    """Hand a file or acmanager:// URI to Content Manager (it reuses a running instance)."""
    subprocess.Popen([str(cm_path()), *args])


# -- install ---------------------------------------------------------------------

def install(track_dir: Path) -> None:
    tid = track_dir.name
    dest = ac_root() / "content" / "tracks" / tid
    if dest.exists():
        attribution = dest / "ATTRIBUTION.txt"
        if not (attribution.exists() and MARKER in attribution.read_text(encoding="utf-8", errors="ignore")):
            sys.exit(f"{dest} exists and was not made by mapcreator; refusing to overwrite it")
        shutil.rmtree(dest)
    shutil.copytree(track_dir, dest)
    # AC caches AI grids and payloads per track; stale ones survive a reinstall.
    cache = ac_root() / "cache"
    removed = 0
    for sub in ("ai_grids", "ai_payloads"):
        for p in (cache / sub).glob(f"{tid}__*"):
            p.unlink()
            removed += 1
    print(f"installed {tid} -> {dest} (cleared {removed} cached AI files)")


# -- race.ini --------------------------------------------------------------------

def _race_ini() -> Path:
    return ac_docs() / "cfg" / "race.ini"


def _patched_race_ini(tid: str, layout: str, car: str) -> str:
    cp = configparser.ConfigParser(strict=False, interpolation=None)
    cp.optionxform = str
    cp.read(_race_ini(), encoding="utf-8-sig")
    for section, values in {
        "RACE": {"TRACK": tid, "CONFIG_TRACK": layout, "MODEL": car, "CARS": "1", "PENALTIES": "0"},
        "CAR_0": {"MODEL": "-", "DRIVER_NAME": "Test"},
        "SESSION_0": {"NAME": "Practice", "TYPE": "1", "DURATION_MINUTES": "0", "SPAWN_SET": "PIT"},
        "AUTOSPAWN": {"ACTIVE": "1"},
    }.items():
        if not cp.has_section(section):
            cp.add_section(section)
        for k, v in values.items():
            cp.set(section, k, v)
    buf = io.StringIO()
    cp.write(buf, space_around_delimiters=False)
    return buf.getvalue()


def prepare(tid: str, layout: str, car: str) -> None:
    ini = _race_ini()
    backup = ini.with_suffix(".ini.mapcreator-backup")
    if not backup.exists():
        shutil.copy2(ini, backup)
    ini.write_text(_patched_race_ini(tid, layout, car), encoding="utf-8")
    print(f"race.ini set to {tid}/{layout or '(main)'} with {car}; backup at {backup}")


def restore() -> None:
    ini = _race_ini()
    backup = ini.with_suffix(".ini.mapcreator-backup")
    if not backup.exists():
        sys.exit("no backup to restore")
    shutil.copy2(backup, ini)
    backup.unlink()
    print("race.ini restored")


def launch(tid: str, layout: str, car: str) -> None:
    """Start a fully specified practice session through CM's acmanager://race/config route.

    CM writes the race.ini itself and starts AC through the user's configured
    starter. AC still waits in the pits menu until Drive is pressed.
    """
    path = Path(tempfile.gettempdir()) / f"mapcreator_{tid}_{layout or 'main'}_race.ini"
    path.write_text(_patched_race_ini(tid, layout, car), encoding="utf-8")
    uri = f"acmanager://race/config?configFile={quote(str(path), safe='')}"
    _cm(uri)
    print(f"asked Content Manager to start {tid}/{layout or '(main)'} with {car}")


# -- checks ----------------------------------------------------------------------

def check_log(tid: str) -> int:
    logs = ac_docs() / "logs"
    lines = (logs / "log.txt").read_text(encoding="utf-8", errors="ignore").splitlines()
    loaded = any(f"LOADING MODEL content/tracks/{tid}" in ln for ln in lines)
    physics = any(ln.strip() == "STARTING PHYSICS ENGINE" for ln in lines)
    errors = [ln for ln in lines if tid in ln and "ERROR:" in ln and f"NO STAT FOR {tid}" not in ln
              and not ln.startswith("Saving replay:")]
    print(f"track model loaded: {loaded}\nphysics started: {physics}\nerrors naming the track: {len(errors)}")
    for ln in errors[:20]:
        print("  ", ln)
    csp = logs / "custom_shaders_patch.log"
    if csp.exists():
        csp_errors = [ln for ln in csp.read_text(encoding="utf-8", errors="ignore").splitlines()
                      if "ERROR" in ln.upper() and (tid in ln or "ext_config" in ln.lower())]
        print(f"CSP log errors naming the track or its config: {len(csp_errors)}")
        for ln in csp_errors[:20]:
            print("  ", ln)
    return 0 if loaded and physics and not errors else 1


def probe(samples: int = 3) -> int:
    """Physics page: speed, wheel loads, suspension. Graphics page: status and car position."""
    try:
        phys = mmap.mmap(-1, 512, tagname="Local\\acpmf_physics", access=mmap.ACCESS_READ)
        graph = mmap.mmap(-1, 512, tagname="Local\\acpmf_graphics", access=mmap.ACCESS_READ)
    except OSError as e:
        print(f"shared memory not available (is AC running?): {e}")
        return 1
    ok = True
    for i in range(samples):
        phys.seek(0)
        p = phys.read(200)
        graph.seek(0)
        g = graph.read(264)
        speed = struct.unpack_from("<f", p, 28)[0]
        loads = struct.unpack_from("<4f", p, 72)
        status = struct.unpack_from("<i", g, 4)[0]  # 0 off, 1 replay, 2 live, 3 pause
        progress = struct.unpack_from("<f", g, 248)[0]
        pos = struct.unpack_from("<3f", g, 252)
        good = all(v == v and v > 100 for v in loads)
        ok &= good
        print(f"status {status} speed {speed:6.1f} km/h  wheel loads {[round(v) for v in loads]} N  "
              f"position {[round(c, 2) for c in pos]}  progress {progress:.3f}  "
              f"{'OK' if good else 'NOT ALL WHEELS LOADED'}")
        if i < samples - 1:
            time.sleep(1)
    return 0 if ok else 1


def results() -> int:
    """Times from AC's race_out.json. Whether point-to-point runs appear as laps is still to be confirmed."""
    path = ac_docs() / "out" / "race_out.json"
    if not path.exists():
        print(f"{path} not found")
        return 1
    data = json.loads(path.read_text(encoding="utf-8", errors="ignore"))
    print(f"track: {data.get('track')}")
    for s in data.get("sessions", []):
        laps = s.get("laps", [])
        print(f"session {s.get('name')} ({len(laps)} laps)")
        for lap in laps:
            t = lap.get("time", 0)
            print(f"  lap {lap.get('lap')}: {t / 1000:.3f} s  cuts {lap.get('cuts')}  sectors {lap.get('sectors')}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="ac_harness")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("showroom")
    p.add_argument("kn5", type=Path)
    p = sub.add_parser("install")
    p.add_argument("track_dir", type=Path)
    p = sub.add_parser("install-cm")
    p.add_argument("zip", type=Path)
    for name in ("prepare", "launch"):
        p = sub.add_parser(name)
        p.add_argument("track_id")
        p.add_argument("--layout", default="forward", help="layout folder; empty string for single-layout tracks")
        p.add_argument("--car", default="abarth500")
    sub.add_parser("restore")
    p = sub.add_parser("check-log")
    p.add_argument("track_id")
    sub.add_parser("probe")
    sub.add_parser("results")
    args = ap.parse_args(argv)
    if args.cmd == "showroom":
        _cm(str(args.kn5.resolve()))
    elif args.cmd == "install":
        install(args.track_dir)
    elif args.cmd == "install-cm":
        _cm(str(args.zip.resolve()))
    elif args.cmd == "prepare":
        prepare(args.track_id, args.layout, args.car)
    elif args.cmd == "launch":
        launch(args.track_id, args.layout, args.car)
    elif args.cmd == "restore":
        restore()
    elif args.cmd == "check-log":
        return check_log(args.track_id)
    elif args.cmd == "probe":
        return probe()
    elif args.cmd == "results":
        return results()
    return 0


if __name__ == "__main__":
    sys.exit(main())
