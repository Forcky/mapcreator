"""In-game test harness for development (Windows, Assetto Corsa installed). UNTESTED until M3.

Never part of a public build: AC's licence covers personal use only.

    python harness/ac_harness.py install  out/<id>/05_track/<id>
    python harness/ac_harness.py prepare  <id> [--layout forward]   # back up and patch cfg/race.ini
    (start the session from Content Manager or the AC launcher, drive, then quit the game)
    python harness/ac_harness.py check-log <id>                      # read log.txt after AC closes
    python harness/ac_harness.py probe                               # while driving: wheels on the ground?
    python harness/ac_harness.py restore                             # put race.ini back

AC root comes from MAPCREATOR_AC_ROOT or `ac_root` in config.local.toml.
Documents folder: MAPCREATOR_AC_DOCS, default ~/Documents/Assetto Corsa.

Load-test rules follow an open-source generator's harness (see THIRD_PARTY_NOTICES.md):
- The log must show `LOADING MODEL content/tracks/<id>` and `STARTING PHYSICS ENGINE`.
- There must be no `ERROR:` line naming the track, except `ERROR: NO STAT FOR <id>`.
- The physics page must show all four wheel loads above 100 N.
"""

from __future__ import annotations

import argparse
import configparser
import mmap
import os
import shutil
import struct
import sys
import time
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = "generated by mapcreator"


def ac_root() -> Path:
    value = os.environ.get("MAPCREATOR_AC_ROOT")
    cfg = ROOT / "config.local.toml"
    if not value and cfg.exists():
        value = tomllib.loads(cfg.read_text(encoding="utf-8")).get("ac_root")
    if not value:
        sys.exit("set MAPCREATOR_AC_ROOT or ac_root in config.local.toml")
    path = Path(value)
    if not (path / "acs.exe").exists():
        sys.exit(f"{path} does not contain acs.exe")
    return path


def ac_docs() -> Path:
    return Path(os.environ.get("MAPCREATOR_AC_DOCS", Path.home() / "Documents" / "Assetto Corsa"))


def install(track_dir: Path) -> None:
    tid = track_dir.name
    dest = ac_root() / "content" / "tracks" / tid
    if dest.exists():
        attribution = dest / "ATTRIBUTION.txt"
        if not (attribution.exists() and MARKER in attribution.read_text(encoding="utf-8", errors="ignore")):
            sys.exit(f"{dest} exists and was not made by mapcreator; refusing to overwrite it")
        shutil.rmtree(dest)
    shutil.copytree(track_dir, dest)
    # AC caches AI grids and payloads per track; stale ones survive a reinstall.
    cache = ac_root() / "cache"
    removed = 0
    for sub in ("ai_grids", "ai_payloads"):
        for p in (cache / sub).glob(f"{tid}__*"):
            p.unlink()
            removed += 1
    print(f"installed {tid} -> {dest} (cleared {removed} cached AI files)")


def _race_ini() -> Path:
    return ac_docs() / "cfg" / "race.ini"


def prepare(tid: str, layout: str, car: str) -> None:
    ini = _race_ini()
    backup = ini.with_suffix(".ini.mapcreator-backup")
    if not backup.exists():
        shutil.copy2(ini, backup)
    cp = configparser.ConfigParser(strict=False, interpolation=None)
    cp.optionxform = str
    cp.read(ini, encoding="utf-8-sig")
    for section, values in {
        "RACE": {"TRACK": tid, "CONFIG_TRACK": layout, "MODEL": car, "CARS": "1", "PENALTIES": "0"},
        "SESSION_0": {"NAME": "Practice", "TYPE": "1", "DURATION_MINUTES": "0", "SPAWN_SET": "PIT"},
    }.items():
        if not cp.has_section(section):
            cp.add_section(section)
        for k, v in values.items():
            cp.set(section, k, v)
    with ini.open("w", encoding="utf-8") as f:
        cp.write(f, space_around_delimiters=False)
    print(f"race.ini set to {tid}/{layout or '(main)'} with {car}; backup at {backup}")


def restore() -> None:
    ini = _race_ini()
    backup = ini.with_suffix(".ini.mapcreator-backup")
    if not backup.exists():
        sys.exit("no backup to restore")
    shutil.copy2(backup, ini)
    backup.unlink()
    print("race.ini restored")


def check_log(tid: str) -> int:
    log = ac_docs() / "logs" / "log.txt"
    lines = log.read_text(encoding="utf-8", errors="ignore").splitlines()
    loaded = any(f"LOADING MODEL content/tracks/{tid}" in ln for ln in lines)
    physics = any(ln.strip() == "STARTING PHYSICS ENGINE" for ln in lines)
    errors = [ln for ln in lines if tid in ln and "ERROR:" in ln and f"NO STAT FOR {tid}" not in ln
              and not ln.startswith("Saving replay:")]
    print(f"track model loaded: {loaded}\nphysics started: {physics}\nerrors naming the track: {len(errors)}")
    for ln in errors[:20]:
        print("  ", ln)
    return 0 if loaded and physics and not errors else 1


def probe(samples: int = 3) -> int:
    """Read the physics shared-memory page: speed, wheel loads and suspension travel."""
    try:
        page = mmap.mmap(-1, 512, tagname="Local\\acpmf_physics", access=mmap.ACCESS_READ)
    except OSError as e:
        print(f"physics page not available (is AC running?): {e}")
        return 1
    ok = True
    for i in range(samples):
        page.seek(0)
        raw = page.read(200)
        packet = struct.unpack_from("<i", raw, 0)[0]
        speed = struct.unpack_from("<f", raw, 28)[0]
        loads = struct.unpack_from("<4f", raw, 72)
        travel = struct.unpack_from("<4f", raw, 184)
        good = all(v == v and v > 100 for v in loads)
        ok &= good
        print(f"packet {packet} speed {speed:6.1f} km/h  wheel loads {[round(v) for v in loads]} N  "
              f"travel {[round(t, 3) for t in travel]} m  {'OK' if good else 'NOT ALL WHEELS LOADED'}")
        if i < samples - 1:
            time.sleep(1)
    return 0 if ok else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="ac_harness")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("install")
    p.add_argument("track_dir", type=Path)
    p = sub.add_parser("prepare")
    p.add_argument("track_id")
    p.add_argument("--layout", default="forward")
    p.add_argument("--car", default="abarth500")
    sub.add_parser("restore")
    p = sub.add_parser("check-log")
    p.add_argument("track_id")
    sub.add_parser("probe")
    args = ap.parse_args(argv)
    if args.cmd == "install":
        install(args.track_dir)
    elif args.cmd == "prepare":
        prepare(args.track_id, args.layout, args.car)
    elif args.cmd == "restore":
        restore()
    elif args.cmd == "check-log":
        return check_log(args.track_id)
    elif args.cmd == "probe":
        return probe()
    return 0


if __name__ == "__main__":
    sys.exit(main())
